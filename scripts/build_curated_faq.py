def humanize_answer(question: str, answer: str) -> str:
    if question in QUESTION_OVERRIDES:
        return QUESTION_OVERRIDES[question]

    text = cleanup_answer_text(answer)

    if "如果用户需要具体的证书编号或检测报告原件" in text:
        text = text.replace(
            "如果用户需要具体的证书编号或检测报告原件，",
            "如果您需要具体的证书编号或检测报告原件，",
        )

    if question.endswith("在哪里？") and text.startswith("就目前资料来看"):
        text = text.replace("就目前资料来看，", "", 1)

    if question.endswith("什么时候成立？") and text.startswith("就目前资料来看"):
        text = text.replace("就目前资料来看，", "", 1)

    if question.endswith("注册资金是多少？") and text.startswith("就目前资料来看"):
        text = text.replace("就目前资料来看，", "", 1)

    if "如果您需要更细的原件或参数，我可以帮您对接人工继续确认" in text and "我可以帮您对接人工继续确认" in text:
        text = text.replace("我可以帮您对接人工继续确认我可以帮您对接人工继续确认", "我可以帮您对接人工继续确认")

    return style_answer_by_batch(question, text)


def style_answer_by_batch(question: str, text: str) -> str:
    if question in COMPANY_BATCH:
        if question.endswith("什么时候成立？") or question.endswith("注册资金是多少？") or question.endswith("在哪里？"):
            return text
        if not text.startswith(("简单说", "可以把它理解为", "核心产品")):
            return f"简单说，{text}"
        return text

    if question in CAPABILITY_BATCH:
        if question.startswith("为什么说") and not text.startswith("核心原因在于"):
            return f"核心原因在于，{text}"
        if question.endswith("怎么样？") and not text.startswith(("这块", "整体上", "可以", "适合")):
            return f"这块表现是不错的。{text}"
        if question.endswith("强吗？") and not text.startswith("这块"):
            return f"这块表现是比较强的。{text}"
        if question.endswith("可以净化空气吗？") and not text.startswith("可以"):
            return f"可以，而且这是它比较核心的功能之一。{text}"
        return text

    if question in EXPERIENCE_BATCH:
        if question.endswith("友好吗？") and not text.startswith(("比较友好", "如果您")):
            return f"整体上比较友好。{text}"
        if question.endswith("值不值得？") and not text.startswith("如果"):
            return f"这要看您更在意什么。{text}"
        if question.endswith("是不是噱头？") and not text.startswith(("不是", "更准确地说")):
            return f"更准确地说，它不是靠噱头支撑的。{text}"
        return text

    if question in SCENARIO_BATCH:
        if question.endswith("吗？") and text.startswith(("适合。", "可以。")):
            return text
        if question.endswith("场景？") and not text.startswith(("如果", "这类", "硅藻")):
            return f"能用，而且场景不算窄。{text}"
        return text

    if question in COMMERCIAL_BATCH:
        return text

    return text


def merge_rows() -> list[dict[str, str]]:
    merged = []
    merged.extend(read_csv_rows(BASE_FILE))
    merged.extend(read_csv_rows(REVIEWED_KEEP_FAQ_FILE))

    if LEGACY_CURATED_FILE.exists():
        merged.extend(read_csv_rows(LEGACY_CURATED_FILE))

    deduped: list[dict[str, str]] = []
    seen_questions: set[str] = set()

    for row in merged:
        question = normalize_question((row.get("question") or ""))
        answer = (row.get("answer") or "").strip()
        if not question or not answer or question in seen_questions:
            continue

        seen_questions.add(question)
        deduped.append(
            {
                "question": question,
                "answer": humanize_answer(question, answer),
            }
        )

    return deduped


def main() -> None:
    rows = merge_rows()
    OUT_FILE.parent.mkdir(parents=True, exist_ok=True)

    with OUT_FILE.open("w", encoding="utf-8-sig", newline="") as file:
        writer = csv.DictWriter(file, fieldnames=["question", "answer"])
        writer.writeheader()
        writer.writerows(rows)

    print(f"Wrote {len(rows)} rows to {OUT_FILE}")


if __name__ == "__main__":
    main()
